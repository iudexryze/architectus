function hexToRgba(hex, alpha) {
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return 'rgba(' + r + ', ' + g + ', ' + b + ', ' + alpha.toFixed(3) + ')';
}

function generateCSS(s) {
  const sc    = (s.scanlinesOpacity / 100).toFixed(3);
  const gi    = s.ryzeGlowIntensity / 100;
  const pulse = (s.cursorPulseSpeed / 10).toFixed(1);
  const op    = ((s.ryzeOpacity || 100) / 100).toFixed(2);
  const front = (s.ryzeText    || 'IUDEX').replace(/\\/g,'\\\\').replace(/"/g,'\\"');
  const back  = (s.ryzeBackText|| 'RYZE' ).replace(/\\/g,'\\\\').replace(/"/g,'\\"');
  const glitch = s.ryzeGlitchEnabled && (s.ryzeGlitchIntensity || 0) > 0;
  const gx    = (s.ryzeGlitchIntensity || 40) / 100;
  const gs    = Math.max(2, Math.round(gx * 8)); // shake / CA offset px
  const cBlur = Math.max(2, Math.round(gx * 6)); // chromatic aberration blur px

  let c = '/* Varun\'s Architectus — generated by Architectus Directives */\n\n';

  c += '/* --- Syntax glow --- */\n';
  if (s.syntaxGlowEnabled !== false) {
    c += '.mtk1  { text-shadow: 0 0 6px rgba(255,255,255,0.6); }\n';
    c += '.mtk3  { text-shadow: 0 0 8px ' + s.colorStrings + ', 0 0 16px ' + s.colorStrings + '; }\n';
    c += '.mtk4  { text-shadow: 0 0 8px ' + s.colorTypes + ', 0 0 16px ' + s.colorTypes + '; }\n';
    c += '.mtk5  { text-shadow: 0 0 8px ' + s.colorKeywords + ', 0 0 14px ' + s.colorKeywords + '; }\n';
    c += '.mtk6  { text-shadow: 0 0 8px ' + s.colorNumbers + ', 0 0 14px ' + s.colorNumbers + '; }\n';
    c += '.mtk7  { text-shadow: 0 0 8px ' + s.colorFunctions + ', 0 0 14px ' + s.colorFunctions + '; }\n';
    c += '.mtk8  { text-shadow: 0 0 6px ' + s.colorVariables + ', 0 0 12px ' + s.colorVariables + '; }\n';
    c += '.mtk9  { text-shadow: 0 0 8px ' + s.colorErrors + ', 0 0 14px ' + s.colorErrors + '; }\n';
    c += '.mtk12 { text-shadow: 0 0 6px ' + s.colorComments + '; }\n';
  } else {
    c += '.mtk1,.mtk3,.mtk4,.mtk5,.mtk6,.mtk7,.mtk8,.mtk9,.mtk12 { text-shadow: none; }\n';
  }
  c += '\n';

  c += '/* --- Cursor --- */\n';
  c += '.cursor { box-shadow: 0 0 6px 2px ' + s.cursorColor1 + ', 0 0 14px 4px ' + s.cursorColor2 + '; animation: cursor-pulse ' + pulse + 's ease-in-out infinite; }\n';
  c += '@keyframes cursor-pulse {\n';
  c += '  0%,100% { box-shadow: 0 0 6px 2px ' + s.cursorColor1 + ', 0 0 14px 4px ' + s.cursorColor2 + '; }\n';
  c += '  50%      { box-shadow: 0 0 12px 4px ' + s.cursorColor1 + ', 0 0 28px 8px ' + s.cursorColor2 + '; }\n}\n\n';

  c += '/* --- Scanlines on editor-container (frees ::after for back-face text) --- */\n';
  c += '.editor-container { position: relative; }\n';
  if (s.scanlinesEnabled) {
    c += '.editor-container::after {\n';
    c += '  content: ""; position: absolute; top: 0; left: 0; right: 0; bottom: 0;\n';
    c += '  background: repeating-linear-gradient(to bottom, transparent 0px, transparent 3px, rgba(0,0,0,' + sc + ') 3px, rgba(0,0,0,' + sc + ') 4px);\n';
    c += '  pointer-events: none; z-index: 100;\n}\n\n';
  }

  // Background glitch
  const bgA1 = hexToRgba(s.ryzeGlowColor, 0.07 * gx);
  const bgA2 = hexToRgba(s.ryzeExtrudeColor, 0.05 * gx);
  if (glitch) {
    c += '/* --- Background glitch --- */\n';
    c += '.editor-container::before {\n';
    c += '  content: ""; position: absolute; top: 0; left: 0; right: 0; bottom: 0;\n';
    c += '  pointer-events: none; z-index: 5; opacity: 0;\n';
    c += '  animation: bg-glitch 11s steps(1) infinite;\n}\n';
    c += '@keyframes bg-glitch {\n';
    c += '  0%, 84%, 92%, 100% { opacity: 0; background: none; }\n';
    c += '  84.5% { opacity: 1; background: linear-gradient(to bottom, transparent 22%, ' + bgA1 + ' 22%, ' + bgA1 + ' 23%, transparent 23%, transparent 58%, ' + bgA2 + ' 58%, ' + bgA2 + ' 59%, transparent 59%); }\n';
    c += '  85.5% { opacity: 0; background: none; }\n';
    c += '  87%   { opacity: 1; background: linear-gradient(to bottom, transparent 71%, ' + bgA1 + ' 71%, ' + bgA1 + ' 73%, transparent 73%); }\n';
    c += '  88%   { opacity: 0; background: none; }\n';
    c += '  90%   { opacity: 1; background: linear-gradient(to bottom, transparent 41%, ' + bgA2 + ' 41%, ' + bgA2 + ' 42%, transparent 42%); }\n';
    c += '  91%   { opacity: 0; background: none; }\n}\n\n';
  }

  c += '/* --- Editor chrome --- */\n';
  c += '.editor-container .monaco-editor { position: relative; }\n';
  c += '.monaco-editor .current-line { box-shadow: inset 0 0 30px ' + hexToRgba(s.ryzeGlowColor, 0.08) + '; border-color: ' + hexToRgba(s.ryzeGlowColor, 0.25) + ' !important; }\n';
  c += '.monaco-scrollable-element > .scrollbar > .slider { background: ' + hexToRgba(s.scrollbarColor, 0.4) + ' !important; border-radius: 4px; box-shadow: 0 0 6px ' + s.scrollbarColor + '; }\n';
  c += '.monaco-scrollable-element > .scrollbar > .slider:hover { background: ' + hexToRgba(s.scrollbarHoverColor, 0.6) + ' !important; box-shadow: 0 0 10px ' + s.scrollbarHoverColor + '; }\n';
  c += '.tab.active { box-shadow: inset 0 -2px 0 ' + s.cursorColor1 + ', 0 0 10px ' + hexToRgba(s.cursorColor1, 0.3) + '; }\n';
  c += '.monaco-list-row.focused { box-shadow: inset 2px 0 0 ' + s.ryzeGlowColor + '; }\n';
  c += '.xterm-cursor-layer .xterm-cursor { box-shadow: 0 0 6px 2px ' + s.colorKeywords + '; }\n';
  c += '.minimap { opacity: 0.6; filter: saturate(1.5) brightness(0.9); }\n\n';

  if (s.ryzeEnabled) {
    const shadow =
      '    1px 1px 0 ' + hexToRgba(s.ryzeExtrudeColor, 0.40) + ',\n' +
      '    2px 2px 0 ' + hexToRgba(s.ryzeExtrudeColor, 0.35) + ',\n' +
      '    3px 3px 0 ' + hexToRgba(s.ryzeExtrudeColor, 0.30) + ',\n' +
      '    4px 4px 0 ' + hexToRgba(s.ryzeExtrudeColor, 0.25) + ',\n' +
      '    5px 5px 0 ' + hexToRgba(s.ryzeExtrudeColor, 0.18) + ',\n' +
      '    6px 6px 0 ' + hexToRgba(s.ryzeExtrudeColor, 0.12) + ',\n' +
      '    7px 7px 0 ' + hexToRgba(s.ryzeGlowColor, 0.08) + ',\n' +
      '    8px 8px 0 ' + hexToRgba(s.ryzeGlowColor, 0.05) + ',\n' +
      '    0 0 40px  ' + hexToRgba(s.ryzeGlowColor, gi) + ',\n' +
      '    0 0 80px  ' + hexToRgba(s.ryzeGlowColor, gi * 0.55) + ',\n' +
      '    0 0 120px ' + hexToRgba(s.ryzeExtrudeColor, gi * 0.33);

    const shared =
      '  position: absolute; top: 50%; left: 50%;\n' +
      '  font-size: clamp(48px,' + s.ryzeSize + 'vw,420px);\n' +
      '  font-weight: 900; font-family: \'Arial Black\',\'Impact\',sans-serif;\n' +
      '  letter-spacing: 0.12em; white-space: nowrap; color: transparent;\n' +
      '  -webkit-text-stroke: 1.5px ' + hexToRgba(s.ryzeGlowColor, 0.35) + ';\n' +
      '  text-shadow:\n' + shadow + ';\n' +
      '  pointer-events: none; z-index: 10; mix-blend-mode: screen; opacity: ' + op + ';\n' +
      '  backface-visibility: hidden; -webkit-backface-visibility: hidden;\n';

    const freq   = s.ryzeGlitchFrequency || 7;
    const freqB  = Math.round(freq * 13 / 9);
    const typing = s.ryzeTypingGlitch;
    const glitchAnimA = glitch ? ', text-glitch-a var(--architectus-freq-a) steps(1) infinite' : '';
    const glitchAnimB = glitch ? ', text-glitch-b var(--architectus-freq-b) steps(1) infinite' : '';
    const typingAnim  = (glitch && typing) ? ', text-glitch-typing 0.22s steps(3) 1' : '';

    c += ':root { --architectus-speed: ' + s.ryzeSpeed + 's;';
    if (glitch) c += ' --architectus-freq-a: ' + freq + 's; --architectus-freq-b: ' + freqB + 's;';
    c += ' }\n';

    c += '/* --- Front/back text flip --- */\n';
    c += '.editor-container .monaco-editor::before,\n.editor-container .monaco-editor::after {\n' + shared + '}\n';
    c += '.editor-container .monaco-editor::before {\n';
    c += '  content: "' + front + '";\n';
    c += '  animation: architectus-front var(--architectus-speed) linear infinite' + glitchAnimA + ';\n}\n';
    c += '.editor-container .monaco-editor::after {\n';
    c += '  content: "' + back + '";\n';
    c += '  animation: architectus-back var(--architectus-speed) linear infinite' + glitchAnimB + ';\n}\n';

    c += '@keyframes architectus-front {\n';
    c += '  from { transform: translate(-50%,-50%) rotateY(0deg); }\n';
    c += '  to   { transform: translate(-50%,-50%) rotateY(360deg); }\n}\n';
    c += '@keyframes architectus-back {\n';
    c += '  from { transform: translate(-50%,-50%) rotateY(180deg); }\n';
    c += '  to   { transform: translate(-50%,-50%) rotateY(540deg); }\n}\n';

    if (glitch) {
      const s0 = '0 0';
      // Chromatic aberration: split extrude color left, glow color right (like the
      // shader's per-segment R/G/B channel offset). Direction alternates per frame.
      // Each jolt frame is immediately followed by a center frame → jolt → center → jolt.
      const ca1 = hexToRgba(s.ryzeExtrudeColor, 0.90);
      const ca2 = hexToRgba(s.ryzeGlowColor,    0.90);
      const ca1d = hexToRgba(s.ryzeExtrudeColor, 0.70);
      const ca2d = hexToRgba(s.ryzeGlowColor,    0.70);
      const b = cBlur;
      const dsLR  = 'drop-shadow(-' + gs + 'px 0 ' + b + 'px ' + ca1 + ') drop-shadow(' + gs + 'px 0 ' + b + 'px ' + ca2 + ')';
      const dsRL  = 'drop-shadow(' + gs + 'px 0 ' + b + 'px ' + ca1 + ') drop-shadow(-' + gs + 'px 0 ' + b + 'px ' + ca2 + ')';
      const dsLRd = 'drop-shadow(-' + Math.round(gs*0.6) + 'px 0 ' + (b+1) + 'px ' + ca1d + ') drop-shadow(' + Math.round(gs*0.6) + 'px 0 ' + (b+1) + 'px ' + ca2d + ')';

      c += '@keyframes text-glitch-a {\n';
      c += '  0%, 84%, 86%, 88%, 90%, 92%, 94%, 100% { filter: none; translate: ' + s0 + '; opacity: ' + op + '; }\n';
      c += '  85% { filter: ' + dsLR  + '; translate: -' + gs + 'px ' + Math.round(gs*0.5) + 'px; opacity: ' + (op*0.95).toFixed(2) + '; }\n';
      c += '  87% { filter: ' + dsRL  + '; translate: '  + Math.round(gs*0.5) + 'px -' + Math.round(gs*0.25) + 'px; opacity: ' + op + '; }\n';
      c += '  89% { filter: ' + dsLRd + '; translate: -' + Math.round(gs*0.5) + 'px ' + Math.round(gs*0.5) + 'px; opacity: ' + (op*0.90).toFixed(2) + '; }\n';
      c += '  91% { filter: ' + dsLR  + '; translate: '  + gs + 'px 0; opacity: ' + (op*0.93).toFixed(2) + '; }\n';
      c += '  93% { filter: ' + dsRL  + '; translate: -' + Math.round(gs*0.25) + 'px ' + Math.round(gs*0.25) + 'px; opacity: ' + (op*0.97).toFixed(2) + '; }\n}\n';

      c += '@keyframes text-glitch-b {\n';
      c += '  0%, 77%, 79%, 81%, 83%, 85%, 87%, 100% { filter: none; translate: ' + s0 + '; opacity: ' + op + '; }\n';
      c += '  78% { filter: ' + dsRL  + '; translate: '  + gs + 'px -' + Math.round(gs*0.5) + 'px; opacity: ' + (op*0.93).toFixed(2) + '; }\n';
      c += '  80% { filter: ' + dsLRd + '; translate: -' + Math.round(gs*0.5) + 'px ' + Math.round(gs*0.25) + 'px; opacity: ' + op + '; }\n';
      c += '  82% { filter: ' + dsLR  + '; translate: '  + Math.round(gs*0.5) + 'px -' + Math.round(gs*0.5) + 'px; opacity: ' + (op*0.90).toFixed(2) + '; }\n';
      c += '  84% { filter: ' + dsRL  + '; translate: -' + gs + 'px ' + Math.round(gs*0.5) + 'px; opacity: ' + (op*0.93).toFixed(2) + '; }\n';
      c += '  86% { filter: ' + dsLRd + '; translate: '  + Math.round(gs*0.25) + 'px -' + Math.round(gs*0.25) + 'px; opacity: ' + (op*0.97).toFixed(2) + '; }\n}\n';

      if (typing) {
        const tgs = Math.max(gs * 2, 8);
        const tb  = Math.max(cBlur + 2, 5);
        const ca1T = hexToRgba(s.ryzeExtrudeColor, 0.95);
        const ca2T = hexToRgba(s.ryzeGlowColor,    0.95);
        const tLR = 'drop-shadow(-' + tgs + 'px 0 ' + tb + 'px ' + ca1T + ') drop-shadow(' + tgs + 'px 0 ' + tb + 'px ' + ca2T + ')';
        const tRL = 'drop-shadow(' + tgs + 'px 0 ' + tb + 'px ' + ca1T + ') drop-shadow(-' + tgs + 'px 0 ' + tb + 'px ' + ca2T + ')';
        const tM  = 'drop-shadow(-' + Math.round(tgs*0.6) + 'px 0 ' + (tb+2) + 'px ' + ca1d + ') drop-shadow(' + Math.round(tgs*0.6) + 'px 0 ' + (tb+2) + 'px ' + ca2d + ')';
        c += '@keyframes text-glitch-typing {\n';
        c += '  0%   { filter: ' + tLR + '; translate: -' + tgs + 'px ' + Math.round(tgs*0.4) + 'px; }\n';
        c += '  33%  { filter: ' + tRL + '; translate: '  + Math.round(tgs*0.8) + 'px -' + Math.round(tgs*0.3) + 'px; }\n';
        c += '  66%  { filter: ' + tM  + '; translate: -' + Math.round(tgs*0.5) + 'px ' + Math.round(tgs*0.5) + 'px; }\n';
        c += '  100% { filter: none; translate: 0 0; }\n}\n';
        c += 'body.architectus-typing .editor-container .monaco-editor::before {\n';
        c += '  animation: architectus-front var(--architectus-speed) linear infinite' + glitchAnimA + typingAnim + ';\n}\n';
        c += 'body.architectus-typing .editor-container .monaco-editor::after {\n';
        c += '  animation: architectus-back var(--architectus-speed) linear infinite' + glitchAnimB + typingAnim + ';\n}\n';
      }
    }
  }

  return c;
}

